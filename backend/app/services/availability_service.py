import hashlib
from app.models.domain import DomainAvailability


class AvailabilityService:
    """
    Simulated mock domain availability service.
    
    NOTE: All statuses generated by this service are simulated mock data
    for developer sandbox testing and UI evaluation.
    """

    RESERVED_AND_POPULAR_NAMES = {
        "google", "apple", "vercel", "render", "meta", "microsoft",
        "stripe", "amazon", "github", "mastertools", "openai", "anthropic",
        "python", "react", "netflix", "spotify", "uber", "airbnb",
        "domain", "domains", "cloud", "server", "tech", "code"
    }

    @classmethod
    def check_availability(cls, name: str, extension: str) -> DomainAvailability:
        """
        Determines mock availability for a given domain and extension.
        Deterministic algorithm ensures consistent results for repeated queries.
        """
        name_clean = name.lower()
        ext_clean = extension.lower()

        # Reserved / Major brands are marked as taken on primary extensions
        if name_clean in cls.RESERVED_AND_POPULAR_NAMES:
            if ext_clean in [".com", ".net", ".org", ".io", ".ai", ".dev"]:
                return DomainAvailability.TAKEN

        # Extremely short domains (<= 3 letters) on major TLDs are taken or premium
        if len(name_clean) <= 3:
            if ext_clean == ".com":
                return DomainAvailability.TAKEN
            if ext_clean in [".io", ".ai", ".dev"]:
                return DomainAvailability.PREMIUM

        # Use SHA-256 hash for deterministic pseudo-random availability
        seed = f"{name_clean}:{ext_clean}".encode("utf-8")
        hash_val = int(hashlib.sha256(seed).hexdigest(), 16) % 100

        # Distribution:
        # 0-14 -> TAKEN (~15%)
        # 15-26 -> PREMIUM (~12%)
        # 27-99 -> AVAILABLE (~73%)
        if hash_val < 15:
            return DomainAvailability.TAKEN
        elif hash_val < 27 and ext_clean in [".com", ".ai", ".io", ".dev"]:
            return DomainAvailability.PREMIUM
        else:
            return DomainAvailability.AVAILABLE
